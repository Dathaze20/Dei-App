import React, { useMemo, useState } from 'react';
import QRCode from 'react-qr-code';
import { useNavigate } from 'react-router-dom';
import useInventory from '../hooks/useInventory';
import { PlusIcon, MinusIcon, TrashIcon, ShareIcon, XIcon, ShoppingCartIcon, HomeIcon, EnvelopeIcon, ClipboardListIcon, CheckCircleIcon, AlertTriangleIcon } from '../components/shared/icons';
import SupplierChip from '../components/SupplierChip';
import { Supplier, Product } from '../types';
import AnimatedPage from '../components/AnimatedPage';
import { motion, AnimatePresence } from 'framer-motion';
import { useTranslation } from '../hooks/useTranslation';
import Modal from '../components/Modal';

interface OrderDetail {
    productId: string;
    quantity: number;
    product: Product;
    supplier: Supplier | undefined;
}

const getEmojiForColor = (colorClass: string): string => {
  const colorMap: { [key: string]: string } = {
    red: '🔴',
    orange: '🟠',
    amber: '🟠',
    yellow: '🟡',
    lime: '🟢',
    green: '🟢',
    emerald: '🟢',
    teal: '🔵',
    cyan: '🔵',
    blue: '🔵',
    indigo: '🟣',
    violet: '🟣',
    purple: '🟣',
    fuchsia: '💖',
    pink: '💖',
    rose: '💖',
    slate: '⚪️',
  };

  // e.g., 'bg-red-800' -> 'red'
  const colorNameMatch = colorClass.match(/bg-([a-z]+)-/);
  const colorName = colorNameMatch ? colorNameMatch[1] : '';
  return colorMap[colorName] || '▪️'; // Default to a black square
};

const itemVariants = {
  hidden: { opacity: 0, x: -50 },
  visible: { opacity: 1, x: 0 },
  exit: { opacity: 0, x: 50, transition: { duration: 0.2 } },
};

const OrderPage: React.FC = () => {
  const { currentOrder, getProductById, getSupplierById, updateOrderItemQuantity, removeFromOrder, deliName, clearOrder } = useInventory();
  const { t } = useTranslation();
  const navigate = useNavigate();
  const [isShareModalOpen, setShareModalOpen] = useState(false);
  const [isCopied, setIsCopied] = useState(false);
  const [isClearConfirmOpen, setClearConfirmOpen] = useState(false);


  const groupedOrder = useMemo(() => {
    const orderDetails: OrderDetail[] = currentOrder.items.map(item => {
      const product = getProductById(item.productId);
      if (!product) return null;
      const supplier = getSupplierById(product.supplierId);
      return { ...item, product, supplier };
    }).filter((item): item is OrderDetail => item !== null);

    const groups: Record<string, { supplier: Supplier; items: OrderDetail[] }> = {};
    for (const item of orderDetails) {
        if (item && item.supplier) {
            if (!groups[item.supplier.id]) {
                groups[item.supplier.id] = { supplier: item.supplier, items: [] };
            }
            groups[item.supplier.id].items.push(item);
        }
    }

    return Object.values(groups).map(group => {
        const subtotal = group.items.reduce((total, item) => total + item.product.costPrice * item.quantity, 0);
        return { ...group, subtotal };
    }).sort((a,b) => a.supplier.name.localeCompare(b.supplier.name));

  }, [currentOrder.items, getProductById, getSupplierById]);


  const overallTotal = useMemo(() => {
    return groupedOrder.reduce((total, group) => total + group.subtotal, 0);
  }, [groupedOrder]);


  const orderTextForSharing = useMemo(() => {
    let text = `🧾 *${deliName.toUpperCase()} - ${t('order').toUpperCase()}* 🧾\n`;
    text += `****************************************\n`;
    text += `Date: ${new Date().toLocaleString()}\n\n`;

    groupedOrder.forEach(group => {
        const emoji = getEmojiForColor(group.supplier.color);
        text += `----------------------------------------\n`;
        text += ` ${emoji} *${group.supplier.name.toUpperCase()}*\n`;
        text += `----------------------------------------\n`;
        group.items.forEach(item => {
            const itemTotal = item.product.costPrice * item.quantity;
            text += `› ${item.quantity} ${t('casesUnit')} - ${item.product.name} (${item.product.flavor})\n`;
            text += `  ($${item.product.costPrice.toFixed(2)}/case) .... $${itemTotal.toFixed(2)}\n\n`;
        });
        text += `*${t('total')} $${group.subtotal.toFixed(2)}*\n`;
        text += `----------------------------------------\n\n`;
    });
    
    text += `========================================\n`;
    text += `    *${t('total').toUpperCase()} $${overallTotal.toFixed(2)}*\n`;
    text += `========================================\n`;
    text += `Generated by DeliOrderNYC App`;

    return text;
  }, [groupedOrder, overallTotal, deliName, t]);
  
  const handleCloseShareModal = () => {
    setShareModalOpen(false);
    setIsCopied(false);
  }
  
  if (currentOrder.items.length === 0) {
    return (
      <AnimatedPage>
        <div className="text-center py-16 bg-white/75 dark:bg-slate-900/75 backdrop-blur-xl rounded-2xl shadow-xl shadow-black/5">
          <ShoppingCartIcon className="mx-auto h-12 w-12 text-slate-400" />
          <h2 className="mt-4 text-2xl font-bold text-slate-800 dark:text-white">{t('orderEmptyTitle')}</h2>
          <p className="text-brand-muted mt-2 max-w-md mx-auto">{t('orderEmptyMessage')}</p>
          <div className="mt-6">
              <motion.button
                  onClick={() => navigate('/')}
                  className="bg-brand-primary hover:bg-brand-primary-hover text-white font-bold py-3 px-6 rounded-lg transition-colors flex items-center gap-2 mx-auto"
                  whileHover={{ scale: 1.05 }}
                  whileTap={{ scale: 0.95 }}
              >
                  <HomeIcon className="h-5 w-5" />
                  <span>{t('browseProducts')}</span>
              </motion.button>
          </div>
        </div>
      </AnimatedPage>
    );
  }

  return (
    <AnimatedPage>
      <div className="bg-white/75 dark:bg-slate-900/75 backdrop-blur-xl rounded-2xl shadow-xl shadow-black/5 p-4 sm:p-6">
        <h1 className="text-3xl font-extrabold text-slate-900 dark:text-white mb-6">{t('currentOrderTitle')}</h1>
        <div className="space-y-6">
          <AnimatePresence>
            {groupedOrder.map(group => (
              <motion.div 
                key={group.supplier.id}
                layout
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0, y: -20 }}
                className="border border-slate-200/80 dark:border-slate-800/80 rounded-lg overflow-hidden"
              >
                <div className="flex justify-between items-center bg-slate-100/70 dark:bg-slate-800/70 p-3">
                    <SupplierChip supplier={group.supplier} />
                    <span className="font-bold text-slate-700 dark:text-slate-200">${group.subtotal.toFixed(2)}</span>
                </div>
                <div className="space-y-2 p-2">
                    <AnimatePresence>
                      {group.items.map(item => (
                      <motion.div 
                        key={item.productId} 
                        className="flex items-center justify-between p-2 rounded-md hover:bg-slate-100 dark:hover:bg-slate-800/50"
                        variants={itemVariants}
                        initial="hidden"
                        animate="visible"
                        exit="exit"
                        layout
                      >
                          <img src={item.product.imageUrl || 'https://placehold.co/100x100/e2e8f0/4a5568?text=N/A'} alt={item.product.name} className="w-12 h-12 object-cover rounded-md me-4 flex-shrink-0 bg-slate-200" />
                          <div className="flex-1">
                            <h3 className="font-bold text-md text-slate-800 dark:text-slate-100">{item.product.name} <span className="text-brand-muted font-normal">({item.product.flavor})</span></h3>
                            <p className="text-sm text-slate-500">{item.quantity} x ${item.product.costPrice.toFixed(2)}/case</p>
                          </div>
                          <div className="flex items-center space-x-2">
                            <motion.button whileTap={{scale: 0.9}} whileHover={{scale: 1.1}} onClick={() => updateOrderItemQuantity(item.productId, item.quantity - 1)} className="p-1.5 rounded-full hover:bg-slate-200 dark:hover:bg-slate-700"><MinusIcon className="h-5 w-5"/></motion.button>
                            <span className="text-lg font-bold w-8 text-center">{item.quantity}</span>
                            <motion.button whileTap={{scale: 0.9}} whileHover={{scale: 1.1}} onClick={() => updateOrderItemQuantity(item.productId, item.quantity + 1)} className="p-1.5 rounded-full hover:bg-slate-200 dark:hover:bg-slate-700"><PlusIcon className="h-5 w-5"/></motion.button>
                          </div>
                          <div className="text-end w-24 ms-4">
                              <p className="font-bold text-md">${(item.product.costPrice * item.quantity).toFixed(2)}</p>
                          </div>
                          <motion.button whileTap={{scale: 0.9}} whileHover={{scale: 1.1}} onClick={() => removeFromOrder(item.productId)} className="ms-4 p-2 rounded-full text-red-500 hover:text-red-600 hover:bg-red-100 dark:hover:bg-red-900/50 transition-colors"><TrashIcon className="h-5 w-5"/></motion.button>
                      </motion.div>
                      ))}
                    </AnimatePresence>
                </div>
              </motion.div>
            ))}
          </AnimatePresence>
        </div>
        <div className="mt-8 pt-6 border-t border-slate-200 dark:border-slate-800 flex flex-col sm:flex-row justify-between items-center gap-4">
          <div className="text-3xl font-bold">
            <span className="text-slate-500 dark:text-slate-400">{t('total')} </span>
            <span className="text-slate-900 dark:text-white">${overallTotal.toFixed(2)}</span>
          </div>
          <div className="flex items-center gap-2 sm:gap-4 flex-wrap justify-center">
               <motion.button
                  onClick={() => setClearConfirmOpen(true)}
                  className="flex items-center gap-2 bg-red-600 hover:bg-red-700 text-white font-bold py-3 px-5 rounded-lg transition-colors"
                  whileHover={{ scale: 1.05 }}
                  whileTap={{ scale: 0.95 }}
              >
                  <TrashIcon className="h-5 w-5"/>
                  <span>{t('clearOrder')}</span>
              </motion.button>
              <motion.button
                  onClick={() => setShareModalOpen(true)}
                  className="flex items-center gap-2 bg-brand-primary hover:bg-brand-primary-hover text-white font-bold py-3 px-5 rounded-lg transition-colors"
                  whileHover={{ scale: 1.05 }}
                  whileTap={{ scale: 0.95 }}
              >
                  <ShareIcon className="h-5 w-5"/>
                  <span>{t('share')}</span>
              </motion.button>
          </div>
        </div>
        <AnimatePresence>
        {isShareModalOpen && (
            <motion.div 
              className="fixed inset-0 bg-black/50 backdrop-blur-lg z-50 flex justify-center items-center p-4" onClick={handleCloseShareModal}
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              exit={{ opacity: 0 }}
            >
                <motion.div 
                  className="bg-slate-100 dark:bg-slate-900 rounded-2xl shadow-2xl w-full max-w-md p-6 ring-1 ring-black/5 dark:ring-white/10" 
                  onClick={(e) => e.stopPropagation()}
                  initial={{ scale: 0.9, opacity: 0, y: 20 }}
                  animate={{ scale: 1, opacity: 1, y: 0 }}
                  exit={{ scale: 0.9, opacity: 0, y: 20 }}
                  transition={{ type: 'spring', stiffness: 400, damping: 30 }}
                >
                    <div className="flex justify-between items-center mb-4">
                        <h2 className="text-2xl font-bold text-slate-900 dark:text-white">{t('share')} {t('order')}</h2>
                        <motion.button onClick={handleCloseShareModal} className="p-2 rounded-full hover:bg-slate-200 dark:hover:bg-slate-800" whileHover={{scale: 1.1, rotate: 90}}><XIcon className="h-6 w-6" /></motion.button>
                    </div>
                    <p className="mb-4 text-sm text-slate-600 dark:text-slate-400">Scan the QR code, or share the order details via text message or by copying.</p>
                    <div className="flex justify-center p-4 bg-slate-200/70 dark:bg-slate-800/70 rounded-lg">
                        <div className="bg-white p-2 rounded-md shadow-inner">
                            <QRCode value={orderTextForSharing} size={200} title="Deli Order Details"/>
                        </div>
                    </div>
                    <div className="mt-4">
                        <textarea
                            readOnly
                            value={orderTextForSharing}
                            className="w-full h-48 p-3 border border-slate-300 dark:border-slate-700 rounded-md bg-white dark:bg-slate-800/50 focus:outline-none font-mono text-xs"
                        />
                    </div>
                    <div className="mt-4 grid grid-cols-1 sm:grid-cols-2 gap-3">
                      <motion.button
                          onClick={() => {
                              navigator.clipboard.writeText(orderTextForSharing);
                              setIsCopied(true);
                              setTimeout(() => setIsCopied(false), 2000);
                          }}
                          disabled={isCopied}
                          className="flex items-center justify-center gap-2 w-full bg-slate-200 dark:bg-slate-700 hover:bg-slate-300 dark:hover:bg-slate-600 text-slate-800 dark:text-slate-100 font-bold py-3 px-4 rounded-lg transition-colors disabled:opacity-70"
                          whileTap={{ scale: 0.95 }}
                      >
                          {isCopied ? (
                              <>
                                  <CheckCircleIcon className="h-5 w-5 text-green-500"/>
                                  <span>{t('copied')}</span>
                              </>
                          ) : (
                              <>
                                  <ClipboardListIcon className="h-5 w-5"/>
                                  <span>{t('copyText')}</span>
                              </>
                          )}
                      </motion.button>
                      <motion.a
                          href={`sms:?&body=${encodeURIComponent(orderTextForSharing)}`}
                          className="flex items-center justify-center gap-2 w-full bg-brand-primary hover:bg-brand-primary-hover text-white font-bold py-3 px-4 rounded-lg transition-colors"
                          whileTap={{ scale: 0.95 }}
                      >
                          <EnvelopeIcon className="h-5 w-5" />
                          <span>{t('sendAsText')}</span>
                      </motion.a>
                  </div>
                </motion.div>
            </motion.div>
        )}
        </AnimatePresence>
        <Modal isOpen={isClearConfirmOpen} onClose={() => setClearConfirmOpen(false)} title={t('clearOrderConfirmationTitle')}>
            <div className="text-center p-4">
                <AlertTriangleIcon className="mx-auto h-12 w-12 text-red-500" />
                <p className="mt-4 text-slate-600 dark:text-slate-300">{t('clearOrderConfirmationMessage')}</p>
                <div className="mt-6 flex justify-center gap-4">
                    <motion.button
                        onClick={() => setClearConfirmOpen(false)}
                        className="py-2 px-6 rounded-lg bg-slate-200 dark:bg-slate-600 hover:bg-slate-300 dark:hover:bg-slate-500 font-semibold active:scale-98"
                        whileHover={{ scale: 1.05 }}
                        whileTap={{ scale: 0.95 }}
                    >
                        {t('cancel')}
                    </motion.button>
                    <motion.button
                        onClick={() => {
                            clearOrder();
                            setClearConfirmOpen(false);
                        }}
                        className="py-2 px-6 rounded-lg bg-red-600 text-white hover:bg-red-700 font-semibold active:scale-98"
                        whileHover={{ scale: 1.05 }}
                        whileTap={{ scale: 0.95 }}
                    >
                        {t('confirmClear')}
                    </motion.button>
                </div>
            </div>
        </Modal>
      </div>
    </AnimatedPage>
  );
};

export default OrderPage;