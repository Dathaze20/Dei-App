import { readFileSync } from 'fs';
import { describe, expect, it } from 'vitest';
import { translations } from '../contexts/LanguageContext';
import { OrderItem, Product, Supplier } from '../types';
import { OrderTextKey, buildOrderSummary, buildOrderText, getEmojiForColor } from './orderSummary';

const REAL = JSON.parse(readFileSync('fixtures/exports/pr1-b291176-arizona-demo.json', 'utf8')).raw as Record<string, string>;
const products: Product[] = JSON.parse(REAL.inventory_products);
const suppliers: Supplier[] = JSON.parse(REAL.inventory_suppliers);
const arizonaOrder: OrderItem[] = JSON.parse(REAL.inventory_currentOrder).items;
const getProduct = (id: string) => products.find(p => p.id === id);
const getSupplier = (id: string) => suppliers.find(s => s.id === id);
const NOW = new Date('2026-10-15T13:05:00.000Z');
const tFor = (lang: 'en' | 'es' | 'ar') => (key: OrderTextKey) => translations[lang][key];
const summarize = (items: OrderItem[]) => buildOrderSummary(items, getProduct, getSupplier);
const textOf = (items: OrderItem[], lang: 'en' | 'es' | 'ar' = 'en') => buildOrderText(summarize(items), 'DeliOrderNYC', NOW, tFor(lang));

/** The share text exactly as OrderPage built it before C1 (copied from main at ed0e562). */
const legacyOrderText = (items: OrderItem[], deliName: string, t: (key: 'order' | 'casesUnit' | 'total') => string) => {
  const groups: Record<string, { supplier: Supplier; items: { quantity: number; product: Product }[] }> = {};
  for (const item of items) {
    const product = getProduct(item.productId)!;
    const supplier = getSupplier(product.supplierId)!;
    (groups[supplier.id] ??= { supplier, items: [] }).items.push({ quantity: item.quantity, product });
  }
  const grouped = Object.values(groups)
    .map(g => ({ ...g, subtotal: g.items.reduce((total, item) => total + item.product.costPrice * item.quantity, 0) }))
    .sort((a, b) => a.supplier.name.localeCompare(b.supplier.name));
  const overallTotal = grouped.reduce((total, g) => total + g.subtotal, 0);
  let text = `🧾 *${deliName.toUpperCase()} - ${t('order').toUpperCase()}* 🧾\n`;
  text += `****************************************\n`;
  text += `Date: ${NOW.toLocaleString()}\n\n`;
  grouped.forEach(group => {
    const emoji = getEmojiForColor(group.supplier.color);
    text += `----------------------------------------\n`;
    text += ` ${emoji} *${group.supplier.name.toUpperCase()}*\n`;
    text += `----------------------------------------\n`;
    group.items.forEach(item => {
      const itemTotal = item.product.costPrice * item.quantity;
      text += `› ${item.quantity} ${t('casesUnit')} - ${item.product.name} (${item.product.flavor})\n`;
      text += `  ($${item.product.costPrice.toFixed(2)}/case) .... $${itemTotal.toFixed(2)}\n\n`;
    });
    text += `*${t('total')} $${group.subtotal.toFixed(2)}*\n`;
    text += `----------------------------------------\n\n`;
  });
  text += `========================================\n`;
  text += `    *${t('total').toUpperCase()} $${overallTotal.toFixed(2)}*\n`;
  text += `========================================\n`;
  text += `Generated by DeliOrderNYC App`;
  return text;
};

const turkey = { productId: 'bh_turkey', quantity: 1, unit: 'item' as const };
const american = { productId: 'bh_american', quantity: 2, unit: 'item' as const };
const boarsHeadSection = (text: string) => text.slice(text.indexOf("BOAR'S HEAD"), text.indexOf('----------------------------------------\n\n', text.indexOf("BOAR'S HEAD")));

describe('case orders are unchanged', () => {
  it.each(['en', 'es', 'ar'] as const)('the Arizona order text is byte-identical to before C1 (%s) and totals $77.98', lang => {
    const text = textOf(arizonaOrder, lang);
    expect(text).toBe(legacyOrderText(arizonaOrder, 'DeliOrderNYC', tFor(lang)));
    expect(text).toContain('$77.98');
    expect(summarize(arizonaOrder).pricedTotal.toFixed(2)).toBe('77.98');
  });

  it('a larger multi-supplier case order is byte-identical too', () => {
    const items = [
      ...arizonaOrder,
      { productId: products.find(p => p.supplierId === 'sup3')!.id, quantity: 3 },
      { productId: products.find(p => p.supplierId === 'sup4')!.id, quantity: 1 },
    ];
    expect(textOf(items)).toBe(legacyOrderText(items, 'DeliOrderNYC', tFor('en')));
  });
});

describe("Boar's Head weekly list", () => {
  it('new item lines: plain quantities, no case wording, no dollar amounts', () => {
    const summary = summarize([turkey, american]);
    expect(summary.groups[0].lines.map(l => [l.unit, l.priced, l.lineTotal])).toEqual([['item', false, null], ['item', false, null]]);
    expect(summary.hasPriced).toBe(false);
    const text = textOf([turkey, american]);
    expect(text).toContain('› 1 OvenGold Turkey Breast (Roasted)\n');
    expect(text).toContain('› 2 American Cheese (White)\n');
    expect(text).not.toContain('$');
    expect(text).not.toMatch(/case/i);
    expect(text).not.toMatch(/TOTAL/);
    expect(text).toContain('(Not priced)');
  });

  it('a line saved before C1 (no unit) keeps meaning cases, is labelled, and is not priced', () => {
    const legacyLine = { productId: 'bh_turkey', quantity: 1 };
    const summary = summarize([legacyLine]);
    expect(summary.groups[0].lines[0]).toMatchObject({ unit: 'case', olderCaseLine: true, priced: false, lineTotal: null });
    const text = textOf([legacyLine]);
    expect(text).toContain('› 1 case(s) - OvenGold Turkey Breast (Roasted) [earlier order line, in cases]\n');
    expect(text).not.toContain('$');
  });

  it('mixed with Arizona: Arizona is priced as before, the overall figure is a priced subtotal', () => {
    const items = [...arizonaOrder, turkey, american];
    const summary = summarize(items);
    expect(summary.pricedTotal.toFixed(2)).toBe('77.98');
    expect(summary.hasUnpriced).toBe(true);
    const text = textOf(items);
    expect(text).toContain('*Total: $77.98*');
    expect(text).toContain('*PRICED SUBTOTAL: $77.98*');
    expect(text).toContain('Items without a price are not included.');
    expect(text).not.toContain('*TOTAL: $');
    expect(boarsHeadSection(text)).not.toContain('$');
    expect(boarsHeadSection(text)).not.toMatch(/case/i);
  });

  it.each([
    ['es', 'SUBTOTAL CON PRECIO', 'Sin precio'],
    ['ar', 'المجموع الفرعي المسعّر', 'بدون سعر'],
  ] as const)('is translated (%s)', (lang, subtotal, notPriced) => {
    const text = textOf([...arizonaOrder, turkey], lang);
    expect(text).toContain(`*${subtotal}: $77.98*`);
    expect(text).toContain(`(${notPriced})`);
    expect(text).toContain('› 1 OvenGold Turkey Breast (Roasted)\n');
  });
});
