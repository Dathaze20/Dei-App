export interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: keyof typeof translations.en, replacements?: Record<string, string | number>) => string;
  dir: Direction;
}

export const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguage] = useState<Language>(() => {
     if (typeof window !== 'undefined') {
        return (readTracked('language') as Language) || 'en';
     }
     return 'en';
  });

  const [dir, setDir] = useState<Direction>('ltr');

  useEffect(() => {
    const currentDir = language === 'ar' ? 'rtl' : 'ltr';
    setDir(currentDir);
    document.documentElement.lang = language;
    document.documentElement.dir = currentDir;
    guardedSetItem('language', language);
  }, [language]);

  const t = useCallback((key: keyof typeof translations.en, replacements?: Record<string, string | number>): string => {
    let translation = translations[language][key] || translations['en'][key];
    if (replacements) {
      Object.keys(replacements).forEach(rKey => {
        translation = translation.replace(`{${rKey}}`, String(replacements[rKey]));
      });
    }
    return translation;
  }, [language]);

  const value = {
    language,
    setLanguage,
    t,
    dir,
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};